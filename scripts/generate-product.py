#!/usr/bin/env python3
"""Generate the primary identity and explicit, bounded legacy migration names."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    value = json.loads((ROOT / "product.json").read_text())
    if value.get("schema_version") != 1:
        raise ValueError("Unsupported product metadata version")
    for key in ("display_name", "description", "repository"):
        text = value.get(key)
        if not isinstance(text, str) or not text.strip() or len(text) > 120 or any(ord(c) < 32 for c in text):
            raise ValueError("Invalid product metadata: " + key)
    # Primary identities changed by the owner's explicit migration decision.
    # They are not runtime branding knobs or arbitrary data-removal roots.
    expected = {"cli": "deckystream", "plugin": "deckystream", "plugin_directory": "deckystream", "storage_namespace": "deckystream"}
    if value.get("compatibility") != expected:
        raise ValueError("Compatibility identity changes require the migration contract")
    legacy = {"cli": "obsgod", "plugin": "OBSGod", "plugin_directory": "obsgod",
              "storage_namespace": "obsgod", "environment_prefix": "OBSGOD"}
    if value.get("legacy_compatibility") != legacy:
        raise ValueError("Legacy migration identity differs from the supported contract")
    frontend = {"displayName": value["display_name"], "description": value["description"],
                "repository": value["repository"], "compatibility": expected,
                "legacyCompatibility": legacy}
    ts = "// Generated by scripts/generate-product.py from product.json.\n"
    ts += "export const product = " + json.dumps(frontend, indent=2) + " as const;\nexport default product;\n"
    py = '"""Generated by scripts/generate-product.py from product.json."""\n'
    py += "DISPLAY_NAME = " + repr(value["display_name"]) + "\n"
    py += "DESCRIPTION = " + repr(value["description"]) + "\n"
    py += "REPOSITORY = " + repr(value["repository"]) + "\n"
    py += "CLI_NAME = " + repr(expected["cli"]) + "\nPLUGIN_ID = " + repr(expected["plugin"]) + "\n"
    py += "PLUGIN_DIRECTORY = " + repr(expected["plugin_directory"]) + "\n"
    py += "STORAGE_NAMESPACE = " + repr(expected["storage_namespace"]) + "\nENV_PREFIX = 'DECKYSTREAM'\n"
    py += "LEGACY_CLI_NAME = " + repr(legacy["cli"]) + "\nLEGACY_PLUGIN_ID = " + repr(legacy["plugin"]) + "\n"
    py += "LEGACY_PLUGIN_DIRECTORY = " + repr(legacy["plugin_directory"]) + "\n"
    py += "LEGACY_STORAGE_NAMESPACE = " + repr(legacy["storage_namespace"]) + "\n"
    py += "LEGACY_ENV_PREFIX = " + repr(legacy["environment_prefix"]) + "\n"
    return {ROOT / "steamdeck/decky/src/product.ts": ts, ROOT / "steamdeck/product.py": py}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files have drifted")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit("Regenerate product metadata: python3 scripts/generate-product.py")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
